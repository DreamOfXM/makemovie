export type TranslateParams = Record<string, string | number>
export type TranslateFn = (key: string, params?: TranslateParams) => string

interface I18nContextValue {
  locale: Locale
  setLocale(locale: Locale): void
  t: TranslateFn
}

const I18nContext = createContext<I18nContextValue | null>(null)

export const LOCALE_STORAGE_KEY = 'studio-locale'

function readStoredLocale(): Locale | null {
  if (typeof window === 'undefined') return null
  const saved = window.localStorage.getItem(LOCALE_STORAGE_KEY)
  if (saved === 'en' || saved === 'zh') return saved
  return null
}

function detectLocale(): Locale {
  const stored = readStoredLocale()
  if (stored) return stored
  if (typeof window === 'undefined') return 'en'
  return window.navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

const PLURAL_PATTERN = /\{(\w+),\s*plural,\s*one\s*\{([^{}]*)\}\s*other\s*\{([^{}]*)\}\}/g

function interpolate(template: string, params?: TranslateParams): string {
  if (!params) return template
  const pluralized = template.replace(PLURAL_PATTERN, (_match, name: string, one: string, other: string) => {
    const value = String(params[name] ?? '')
    return (value === '1' ? one : other).replace(/#/g, value)
  })
  return pluralized.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match))
}

