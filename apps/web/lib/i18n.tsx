export type TranslateParams = Record<string, string | number>
export type TranslateFn = (key: string, params?: TranslateParams) => string

interface I18nContextValue {
  locale: Locale
  setLocale(locale: Locale): void
  t: TranslateFn
}

const I18nContext = createContext<I18nContextValue | null>(null)

export const LOCALE_STORAGE_KEY = 'studio-locale'

function readStoredLocale(): Locale | null {
  if (typeof window === 'undefined') return null
  const saved = window.localStorage.getItem(LOCALE_STORAGE_KEY)
  if (saved === 'en' || saved === 'zh') return saved
  return null
}

function detectLocale(): Locale {
  const stored = readStoredLocale()
  if (stored) return stored
  if (typeof window === 'undefined') return 'en'
  return window.navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

const PLURAL_PATTERN = /\{(\w+),\s*plural,\s*one\s*\{([^{}]*)\}\s*other\s*\{([^{}]*)\}\}/g

function interpolate(template: string, params?: TranslateParams): string {
  if (!params) return template
  const pluralized = template.replace(PLURAL_PATTERN, (_match, name: string, one: string, other: string) => {
    const value = String(params[name] ?? '')
    return (value === '1' ? one : other).replace(/#/g, value)
  })
  return pluralized.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match))
}

/**
 * Labels enum-ish API values (capability slots, modalities, probe states) that map
 * to prefixed dictionary keys such as `slots.image_gen`. A value with no entry
 * renders as itself instead of leaking the composed key into the UI.
 */
export function translateEnum(t: TranslateFn, prefix: string, value: string): string {
  const key = `${prefix}.${value}`
  const label = t(key)
  return label === key ? value : label
}

export function I18nProvider({ children }: { children: ReactNode }) {
  // Server render and the first client render must agree, so start from 'en'
  // and switch to the stored locale in an effect. Callers that gate on their own
  // loading state never paint the intermediate value.
  const [locale, setLocaleState] = useState<Locale>('en')

  useEffect(() => {
    setLocaleState(detectLocale())
  }, [])

  useEffect(() => {
    document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en'
  }, [locale])

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next)
    window.localStorage.setItem(LOCALE_STORAGE_KEY, next)
    document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en'
  }, [])

  const t = useCallback<TranslateFn>(
    (key, params) => interpolate(dictionaries[locale][key] ?? dictionaries.en[key] ?? key, params),
    [locale],
  )

  const value = useMemo<I18nContextValue>(() => ({ locale, setLocale, t }), [locale, setLocale, t])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n must be used inside I18nProvider')
  return context
}
